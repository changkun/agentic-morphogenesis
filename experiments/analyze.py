def load_ralph_data():
    """Parse .ralph/ JSON files into a DataFrame with one row per (repo, round, role)."""
    rows = []
    for repo_key, cfg in REPOS.items():
        ralph_dir = cfg["path"] / ".ralph"
        for f in sorted(ralph_dir.glob("round-*-*.json")):
            m = re.match(r"round-(\d+)-(thinker|worker)\.json", f.name)
            if not m:
                continue
            rnd, role = int(m.group(1)), m.group(2)
            with open(f) as fh:
                d = json.load(fh)
            usage = d.get("usage", {})
            rows.append({
                "repo": repo_key,
                "round": rnd,
                "role": role,
                "cost_usd": d.get("total_cost_usd", 0),
                "turns": d.get("num_turns", 0),
                "duration_ms": d.get("duration_ms", 0),
                "input_tokens": usage.get("input_tokens", 0),
                "output_tokens": usage.get("output_tokens", 0),
                "cache_read_tokens": usage.get("cache_read_input_tokens", 0),
                "cache_creation_tokens": usage.get("cache_creation_input_tokens", 0),
                "result": d.get("result", ""),
            })
    return pd.DataFrame(rows)


def load_git_history():
    """Extract per-commit LOC changes for the main source file from git log."""
    rows = []
    for repo_key, cfg in REPOS.items():
        result = subprocess.run(
            ["git", "-C", str(cfg["path"]), "log", "--reverse",
             "--format=%H %s", "--numstat", "--", cfg["main_file"]],
            capture_output=True, text=True,
        )
        current_hash = current_msg = None
        for line in result.stdout.splitlines():
            line = line.strip()
            if not line:
                continue
            # numstat line: added\tdeleted\tfilename
            parts = line.split("\t")
            if len(parts) == 3 and parts[0].isdigit():
                added, deleted = int(parts[0]), int(parts[1])
                rows.append({
                    "repo": repo_key,
                    "hash": current_hash,
                    "message": current_msg,
                    "added": added,
                    "deleted": deleted,
                })
            else:
                # commit line: hash message
                sp = line.split(" ", 1)
                current_hash = sp[0]
                current_msg = sp[1] if len(sp) > 1 else ""
    df = pd.DataFrame(rows)
    # Assign sequential round numbers per repo (commits touching main file)
    for repo_key in REPOS:
        mask = df["repo"] == repo_key
        df.loc[mask, "round"] = range(1, mask.sum() + 1)
    df["round"] = df["round"].astype(int)
    return df


def load_source(repo_key):
    """Read the final source file for a repo."""
    cfg = REPOS[repo_key]
    path = cfg["path"] / cfg["main_file"]
    return path.read_text()


# ── Metric Computation ─────────────────────────────────────────────────────


def compute_round_metrics(ralph_df):
    """Aggregate thinker+worker metrics per (repo, round)."""
    grouped = ralph_df.groupby(["repo", "round"]).agg({
        "cost_usd": "sum",
        "turns": "sum",
        "duration_ms": "sum",
        "input_tokens": "sum",
        "output_tokens": "sum",
        "cache_read_tokens": "sum",
        "cache_creation_tokens": "sum",
    }).reset_index()
    grouped["duration_min"] = grouped["duration_ms"] / 60_000
    grouped["total_tokens"] = (
        grouped["input_tokens"] + grouped["output_tokens"]
        + grouped["cache_read_tokens"] + grouped["cache_creation_tokens"]
    )
    return grouped


def compute_code_evolution(git_df):
    """Compute cumulative LOC from git history."""
    dfs = []
    for repo_key in REPOS:
        sub = git_df[git_df["repo"] == repo_key].copy()
        sub["net"] = sub["added"] - sub["deleted"]
        sub["cumulative_loc"] = sub["net"].cumsum()
        dfs.append(sub)
    return pd.concat(dfs, ignore_index=True)


def _count_functions_python(source):
    """Count top-level and method definitions in Python source."""
    tree = ast.parse(source)
    count = 0
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            count += 1
    return count


def _count_functions_c(source):
    """Heuristic count of C function definitions."""
    # Match: type name(...) { at start of line
    return len(re.findall(
        r"^\w[\w\s\*]*\s+(\w+)\s*\([^)]*\)\s*\{",
        source, re.MULTILINE,
    ))


def _cyclomatic_complexity_python(source):
    """Compute mean cyclomatic complexity per function for Python."""
    tree = ast.parse(source)
    complexities = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            cc = 1  # base
            for child in ast.walk(node):
                if isinstance(child, (ast.If, ast.While, ast.For,
                                      ast.ExceptHandler, ast.With,
                                      ast.Assert, ast.comprehension)):
                    cc += 1
                elif isinstance(child, ast.BoolOp):
                    cc += len(child.values) - 1
            complexities.append(cc)
    return np.mean(complexities) if complexities else 0


def _cyclomatic_complexity_c(source):
    """Heuristic cyclomatic complexity for C (regex-based)."""
    # Split into function bodies
    bodies = re.findall(
        r"\)\s*\{(.*?)\n\}",
        source, re.DOTALL,
    )
    if not bodies:
        return 0
    complexities = []
    for body in bodies:
        cc = 1
        cc += len(re.findall(r"\bif\b", body))
        cc += len(re.findall(r"\bfor\b", body))
        cc += len(re.findall(r"\bwhile\b", body))
        cc += len(re.findall(r"\bswitch\b", body))
        cc += len(re.findall(r"\bcase\b", body))
        cc += body.count("&&")
        cc += body.count("||")
        cc += body.count("?")  # ternary
        complexities.append(cc)
    return np.mean(complexities) if complexities else 0


def _count_modes(source, language):
    """Count distinct simulation modes via heuristics."""
    if language == "python":
        # Look for mode enum values or string literals assigned as modes
        modes = set()
        # Common pattern: "mode_name" in mode lists or SimulationMode enum
        for m in re.finditer(r'["\'](\w+)["\']', source):
            val = m.group(1)
            if any(kw in val.lower() for kw in [
                "life", "wire", "ant", "lenia", "sand", "fire",
                "ising", "boids", "fluid", "wave", "erosion",
                "dla", "cyclic", "pendulum", "attractor", "mandelbrot",
                "epidemic", "maze", "ray", "predator", "wator",
                "physarum", "slime", "chimera", "boltzmann", "sph",
                "particle_life", "demo",
            ]):
                modes.add(val)
        # Also check for class definitions that look like modes
        for m in re.finditer(r"class\s+(\w*(?:Mode|Simulation)\w*)", source):
            modes.add(m.group(1))
        # Fallback: count unique mode-like strings in mode selection
        if len(modes) < 3:
            modes = set(re.findall(
                r"(?:mode|MODE)\s*[=:]\s*['\"](\w+)['\"]", source
            ))
        return max(len(modes), 1)
    else:  # C
        modes = set()
        # Count MODE_ and OVERLAY_ enum values
        for m in re.finditer(r"MODE_(\w+)", source):
            modes.add(m.group(1))
        for m in re.finditer(r"OVERLAY_(\w+)", source):
            modes.add(m.group(1))
        # Count static int *_mode variables (explorer pattern)
        for m in re.finditer(r"static\s+int\s+(\w+_mode)\s*=", source):
            modes.add(m.group(1))
        # Count static int show_* variables
        for m in re.finditer(r"static\s+int\s+(show_\w+)\s*=", source):
            modes.add(m.group(1))
        return max(len(modes), 1)


def compute_final_metrics():
    """Compute final codebase metrics for each repo."""
    results = {}
    for repo_key, cfg in REPOS.items():
        source = load_source(repo_key)
        loc = len(source.splitlines())
        lang = cfg["language"]
        if lang == "python":
            func_count = _count_functions_python(source)
            complexity = _cyclomatic_complexity_python(source)
        else:
            func_count = _count_functions_c(source)
            complexity = _cyclomatic_complexity_c(source)
        mode_count = _count_modes(source, lang)
        results[repo_key] = {
            "loc": loc,
            "functions": func_count,
            "modes": mode_count,
            "mean_complexity": round(complexity, 1),
            "language": cfg["language"],
        }
    return results


# ── Feature Categorization ─────────────────────────────────────────────────


def _extract_goal(result_text):
    """Extract the goal from a thinker result."""
    # Pattern 1: **Goal: ...**
    m = re.search(r"\*\*Goal:\s*(.+?)\*\*", result_text)
    if m:
        return m.group(1).strip()
    # Pattern 2: ## ... Goal header followed by content
    m = re.search(r"##\s*(?:Round\s*\d+\s*)?Goal\s*\n+(.+?)(?:\n|$)", result_text)
    if m:
        return m.group(1).strip().strip("*")
    # Pattern 3: **Round N: Feature** or **Feature** in first few lines
    m = re.search(r"\*\*(?:Round\s*\d+[:\s]+)?(.+?)\*\*", result_text[:500])
    if m:
        return m.group(1).strip()
    # Pattern 4: first meaningful sentence
    m = re.match(
        r"(?:Done\.?\s*)?(?:Here'?s?\s+what\s+)?(?:Round\s*\d+\s*)?(.+?)[.\n]",
        result_text,
    )
    if m:
        return m.group(1).strip()
    return result_text[:120]


def categorize_features(ralph_df):
    """Classify each round's goal into feature categories."""
    thinkers = ralph_df[ralph_df["role"] == "thinker"].copy()
    thinkers["goal"] = thinkers["result"].apply(_extract_goal)

    rows = []
    for _, row in thinkers.iterrows():
        goal_lower = row["goal"].lower()
        scores = {}
        for cat, keywords in FEATURE_CATEGORIES.items():
            score = sum(1 for kw in keywords if kw.lower() in goal_lower)
            if score > 0:
                scores[cat] = score
        if scores:
            best_cat = max(scores, key=scores.get)
        else:
            best_cat = "Infrastructure"
        rows.append({
            "repo": row["repo"],
            "round": row["round"],
            "goal": row["goal"],
            "category": best_cat,
        })
    return pd.DataFrame(rows)


def compute_feature_overlap(feature_df):
    """Compute shared vs unique feature categories per repo."""
    repo_cats = {}
    for repo_key in REPOS:
        sub = feature_df[feature_df["repo"] == repo_key]
        repo_cats[repo_key] = set(sub["category"].unique())

    all_cats = set().union(*repo_cats.values())
    shared_all = set.intersection(*repo_cats.values()) if repo_cats else set()

    overlap = {}
    for cat in all_cats:
        repos_with = [r for r, cats in repo_cats.items() if cat in cats]
        overlap[cat] = repos_with
    return overlap, repo_cats


